"use client";

import { useEffect, useState } from "react";
import { Asset, LABEL_TEXT, deleteAsset, downloadBlob, listAssets, saveAsset } from "@/lib/assets";
import { MOODS, Mood, renderMood, toWav } from "@/lib/audio";
import { useObjectUrl } from "@/components/useObjectUrl";
import { icon3d } from "@/lib/library";

const LENGTHS = [8, 16, 30];
const MOOD_ICONS: Record<string, string> = { golden: "lightbulb", night: "rocket", tension: "hourglass", lofi: "microphone" };

export default function AudioPage() {
  const [mood, setMood] = useState<Mood>(MOODS[0]);
  const [length, setLength] = useState(16);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string>();
  const [tracks, setTracks] = useState<Asset[]>([]);

  useEffect(() => {
    listAssets("audio").then(setTracks);
  }, []);

  const render = async () => {
    setBusy(true);
    setError(undefined);
    try {
      const blob = toWav(await renderMood(mood, length));
      const a: Asset = { id: crypto.randomUUID(), kind: "audio", label: "local-synth", createdAt: Date.now(), blob, width: 0, height: 0, presetId: mood.id, durationS: length };
      await saveAsset(a);
      setTracks((t) => [a, ...t]);
    } catch {
      setError("Audio rendering isn't supported in this browser.");
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="mx-auto w-full max-w-4xl px-4 py-10">
      <img src={icon3d("headphones")} alt="" className="mb-3 h-14 w-14" />
      <h1 className="font-display text-5xl uppercase">Soundtracks</h1>
      <p className="mt-2 max-w-xl text-muted">
        Score your clips with a mood bed. Tracks are synthesized on your device, not generated by an AI model, and are
        yours to use.
      </p>

      <div role="radiogroup" aria-label="Mood" className="mt-8 grid gap-3 sm:grid-cols-2">
        {MOODS.map((m) => (
          <button key={m.id} role="radio" aria-checked={m.id === mood.id} onClick={() => setMood(m)}
            className={`rounded-2xl border p-4 text-left transition-colors ${m.id === mood.id ? "border-ember bg-panel-2" : "border-line bg-panel hover:border-muted"}`}>
            <img src={icon3d(MOOD_ICONS[m.id])} alt="" className="float-right h-10 w-10" />
            <span className="block font-semibold">{m.name}</span>
            <span className="text-sm text-muted">{m.hint}</span>
          </button>
        ))}
      </div>

      <div className="mt-6 flex flex-wrap items-center gap-3">
        <div role="radiogroup" aria-label="Length" className="flex rounded-lg bg-panel-2 p-0.5">
          {LENGTHS.map((l) => (
            <button key={l} role="radio" aria-checked={l === length} onClick={() => setLength(l)}
              className={`rounded-md px-3 py-1.5 text-sm tabular-nums ${l === length ? "bg-fg text-bg" : "text-muted hover:text-fg"}`}>
              {l}s
            </button>
          ))}
        </div>
        <button onClick={render} disabled={busy} className="btn-ember rounded-xl px-5 py-2.5 font-semibold disabled:opacity-50">
          {busy ? "Rendering…" : "Render track"}
        </button>
        {error && <p role="alert" className="text-sm text-danger">{error}</p>}
      </div>

      {tracks.length > 0 && (
        <section className="mt-10">
          <h2 className="mb-3 text-sm font-medium text-muted">Your tracks</h2>
          <ul className="space-y-2">
            {tracks.map((t) => (
              <Track key={t.id} asset={t} onDelete={async () => { await deleteAsset(t.id); setTracks((x) => x.filter((y) => y.id !== t.id)); }} />
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}

function Track({ asset, onDelete }: { asset: Asset; onDelete: () => void }) {
  const url = useObjectUrl(asset.blob);
  const mood = MOODS.find((m) => m.id === asset.presetId);
  return (
    <li className="flex flex-wrap items-center gap-3 rounded-xl border border-line bg-panel p-3">
      <span className="min-w-32 text-sm">
        <span className="block font-medium">{mood?.name}</span>
        <span className="text-xs text-muted">{asset.durationS}s · {LABEL_TEXT[asset.label]}</span>
      </span>
      {url && <audio src={url} controls className="h-9 flex-1" />}
      <button onClick={() => downloadBlob(asset.blob, `kiln-${mood?.id}-${asset.id.slice(0, 6)}.wav`)} className="rounded-full bg-panel-2 px-3 py-1 text-xs">Download</button>
      <button onClick={onDelete} className="px-2 text-xs text-muted hover:text-danger">Delete</button>
    </li>
  );
}
